
import csv
import json
import re
from pathlib import Path

BASE_DIR = Path(r"C:\AI\IndicF5")
PROFILE_DIR = Path(
    r"C:\MoneyPrinterTurbo -facelesee ai\storage\indicf5_profiles"
)
API_URL = "http://127.0.0.1:8765"

SAMPLE_FOLDERS = [
    ("female", BASE_DIR / "femaleSample", "ml-female"),
    ("male", BASE_DIR / "maleSample", "ml-male"),
]


def read_mapping(folder):
    mapping_file = folder / "mapping.csv"

    if not mapping_file.is_file():
        print(f"ERROR: Mapping file missing: {mapping_file}")
        return []

    records = []

    with mapping_file.open(
        "r", encoding="utf-8-sig", newline=""
    ) as file:
        reader = csv.DictReader(file)
        required = {"filename", "speaker_id", "text"}

        if not required.issubset(set(reader.fieldnames or [])):
            print(f"ERROR: Invalid mapping columns: {mapping_file}")
            return []

        for row in reader:
            filename = (row.get("filename") or "").strip()
            speaker_id = (row.get("speaker_id") or "").strip()
            transcript = (row.get("text") or "").strip()

            if not filename or not speaker_id or not transcript:
                print(f"SKIP: Incomplete row in {mapping_file}: {row}")
                continue

            # Accept filenames only, not arbitrary paths.
            if Path(filename).name != filename:
                print(f"SKIP: Invalid filename: {filename}")
                continue

            audio_path = (folder / filename).resolve()

            if not audio_path.is_file():
                print(f"SKIP: Audio not found: {audio_path}")
                continue

            if audio_path.suffix.lower() != ".wav":
                print(f"SKIP: Not a WAV file: {audio_path}")
                continue

            records.append({
                "speaker_id": speaker_id,
                "audio_path": str(audio_path),
                "text": transcript,
            })

    return records


def main():
    PROFILE_DIR.mkdir(parents=True, exist_ok=True)

    # Read the source records before modifying any profile files.
    datasets = []
    for gender, folder, prefix in SAMPLE_FOLDERS:
        records = read_mapping(folder)
        datasets.append((gender, prefix, records))

    # Remove old profiles generated by the previous naming convention.
    # This targets only names such as female-mlf_02879.json and
    # male-mlm_07330.json, not unrelated profiles.
    deleted = 0
    old_profile_pattern = re.compile(
        r"^(female|male)-ml[fm]_[A-Za-z0-9_-]+\.json$",
        re.IGNORECASE,
    )

    for profile_file in PROFILE_DIR.glob("*.json"):
        if old_profile_pattern.fullmatch(profile_file.name):
            profile_file.unlink()
            deleted += 1
            print(f"REMOVED OLD PROFILE: {profile_file.name}")

    saved = 0
    errors = 0
    report_rows = []

    for gender, prefix, records in datasets:
        for index, record in enumerate(records, start=1):
            profile_id = f"{prefix}-{index:02d}"
            target = PROFILE_DIR / f"{profile_id}.json"

            profile = {
                "id": profile_id,
                "name": profile_id,
                "reference_audio": record["audio_path"],
                "reference_text": record["text"],
                "api_url": API_URL,
            }

            try:
                # Replace a same-name profile so numbering is repeatable.
                temp = target.with_suffix(".json.tmp")
                with temp.open("w", encoding="utf-8") as file:
                    json.dump(
                        profile,
                        file,
                        ensure_ascii=False,
                        indent=2,
                    )
                    file.write("\n")
                temp.replace(target)

                saved += 1
                status = "saved"
                print(f"SAVED: {profile_id}")

            except Exception as exc:
                errors += 1
                status = f"error: {exc}"
                print(f"ERROR: {profile_id}: {exc}")

            report_rows.append([
                gender,
                record["speaker_id"],
                Path(record["audio_path"]).name,
                profile_id,
                status,
            ])

    report_path = BASE_DIR / "profile_creation_report.csv"
    with report_path.open(
        "w", encoding="utf-8-sig", newline=""
    ) as file:
        writer = csv.writer(file)
        writer.writerow([
            "gender",
            "original_speaker_id",
            "audio_filename",
            "profile_id",
            "status",
        ])
        writer.writerows(report_rows)

    print("\n========== COMPLETE ==========")
    print(f"Old profiles removed: {deleted}")
    print(f"Profiles saved:       {saved}")
    print(f"Errors:               {errors}")
    print(f"Profile directory:    {PROFILE_DIR}")
    print(f"Report:               {report_path}")


if __name__ == "__main__":
    main()
